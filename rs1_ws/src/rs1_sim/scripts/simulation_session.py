#!/usr/bin/env python3
"""Announce one Gazebo lifetime, or stop deployment when that lifetime ends.

Both roles use a steady clock so pausing Gazebo cannot expire a healthy world.
The publisher waits for the first simulation clock message before advertising;
its parent launch shuts down when Gazebo exits.
"""
import json
import os
import time

import rclpy
from rclpy.clock import Clock, ClockType
from rclpy.executors import ExternalShutdownException
from rclpy.node import Node
from rclpy.qos import DurabilityPolicy, QoSProfile, ReliabilityPolicy, qos_profile_sensor_data
from rosgraph_msgs.msg import Clock as ClockMessage
from std_msgs.msg import String


class WorldLease:
    """Monotonic heartbeat tracking independent of ROS simulation time."""

    def __init__(self, expected_id, now, timeout=10.0):
        self.expected_id = expected_id
        self.last_seen = now
        self.timeout = timeout
        self.failure = None

    def observe(self, payload, now):
        instance_id = payload.get("instance_id") if isinstance(payload, dict) else None
        if not isinstance(instance_id, str) or not instance_id:
            return
        if instance_id != self.expected_id:
            self.failure = "The simulation world was replaced or another world is using this ROS domain."
        else:
            self.last_seen = now

    def check(self, now):
        if not self.failure and now - self.last_seen > self.timeout:
            self.failure = "The simulation world stopped publishing its session heartbeat."
        return self.failure


class SimulationSession(Node):
    def __init__(self):
        super().__init__("simulation_session")
        self.declare_parameter("mode", "publish")
        self.declare_parameter("instance_id", "")
        self.declare_parameter("world_instance_id", "")
        self.declare_parameter("world_name", "v2_forest")
        self.declare_parameter("world_file", "")
        self.declare_parameter("ui", False)
        self.declare_parameter("session_id", "manual")
        self.declare_parameter("heartbeat_timeout", 10.0)
        self.should_exit = False
        self.clock_seen = False
        self.mode = self.get_parameter("mode").value
        self.qos = QoSProfile(
            depth=1, reliability=ReliabilityPolicy.RELIABLE,
            durability=DurabilityPolicy.TRANSIENT_LOCAL,
        )
        self.steady_clock = Clock(clock_type=ClockType.STEADY_TIME)
        if self.mode == "guard":
            expected_id = self.get_parameter("world_instance_id").value
            if not expected_id:
                raise ValueError("Guard requires world_instance_id.")
            self.lease = WorldLease(
                expected_id, time.monotonic(), self.get_parameter("heartbeat_timeout").value,
            )
            self.create_subscription(String, "/simulation/session", self.observe, self.qos)
            self.create_timer(0.5, self.check, clock=self.steady_clock)
        elif self.mode == "publish":
            instance_id = self.get_parameter("instance_id").value
            if not instance_id:
                raise ValueError("Publisher requires an instance_id generated by its world launch.")
            self.publisher = self.create_publisher(String, "/simulation/session", self.qos)
            self.payload = json.dumps({
                "instance_id": instance_id,
                "world_name": self.get_parameter("world_name").value,
                "custom_world": bool(self.get_parameter("world_file").value),
                "ui": self.get_parameter("ui").value,
                "ign_partition": os.environ.get("IGN_PARTITION", ""),
                "session_id": self.get_parameter("session_id").value,
            })
            self.create_subscription(ClockMessage, "/clock", self.observe_clock, qos_profile_sensor_data)
            self.create_timer(0.5, self.publish, clock=self.steady_clock)
        else:
            raise ValueError("mode must be publish or guard")

    def observe_clock(self, _message):
        self.clock_seen = True

    def publish(self):
        if self.clock_seen:
            self.publisher.publish(String(data=self.payload))

    def observe(self, message):
        try:
            payload = json.loads(message.data)
        except (ValueError, TypeError):
            return
        self.lease.observe(payload, time.monotonic())
        self.check()

    def check(self):
        reason = self.lease.check(time.monotonic())
        if reason and not self.should_exit:
            self.get_logger().error(reason + " Stopping deployed robot and mission nodes.")
            self.should_exit = True


def main():
    rclpy.init()
    node = None
    try:
        node = SimulationSession()
        while rclpy.ok() and not node.should_exit:
            rclpy.spin_once(node, timeout_sec=0.5)
    except (KeyboardInterrupt, ExternalShutdownException):
        pass
    finally:
        if node is not None:
            node.destroy_node()
        if rclpy.ok():
            rclpy.shutdown()


if __name__ == "__main__":
    main()
